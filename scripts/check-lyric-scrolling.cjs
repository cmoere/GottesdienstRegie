const fs=require('node:fs'),assert=require('node:assert/strict'),ts=require('typescript'),Module=require('node:module');
const file=require('node:path').resolve('src/lyricScrolling.ts'),mod=new Module(file,module);
mod._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,file);
const {lyricPacket,lyricSettings}=mod.exports;
const slides=['V1','C','V2','C','B','C'].map((body,index)=>({id:String(index),itemId:'song',body,title:body,enabled:true,elements:[]}));
const item={id:'song',type:'song',metadata:{},slides},settings={enabled:true};
assert.equal(lyricPacket(item,slides[0]),undefined);
assert.equal(lyricPacket({...item,type:'content'},slides[0],settings),undefined);
assert.equal(lyricPacket({...item,metadata:{lyricScrollingMode:'disabled'}},slides[0],settings),undefined);
assert.equal(lyricSettings({...item,metadata:{lyricScrollingMode:'enabled'}}).enabled,true);
const packet=lyricPacket(item,slides[2],settings);
assert.deepEqual(packet.slides.slice(3).map(page=>page.body),['C','B','C']);
assert.equal(lyricPacket(item,slides[4],settings).currentId,'4');
assert.equal(lyricPacket(item,slides[1],settings).currentId,'1');
slides[3].body='EDITOR CHANGE';assert.equal(packet.slides[3].body,'C');
assert.equal(lyricPacket(item,{...slides[0],title:'Titelfolie'},settings),undefined);
assert.equal(lyricPacket(item,{...slides[0],body:''},settings),undefined);
assert.equal(lyricSettings(item,{durationMs:999999}).durationMs,2000);
const title={...slides[0],id:'title',title:'Titelfolie'},empty={...slides[0],id:'empty',body:''};
const withSpecial={...item,slides:[slides[0],title,empty,slides[1]]};
assert.deepEqual(lyricPacket(withSpecial,slides[0],settings).slides.map(page=>page.id),['0','1'],'Upcoming blocks must contain lyrics, not title/blank pages');
const resolvedSlide={...slides[0],transitionOverride:{type:'cut',duration:0}};
assert.deepEqual(lyricPacket(item,resolvedSlide,settings).slides[0].transitionOverride,resolvedSlide.transitionOverride,'Effective live transition must survive snapshot creation');
console.log('PASS: inheritance, song-only, order, jump, previous, immutable snapshot, title, empty sections, bounds');
