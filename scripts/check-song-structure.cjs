const fs=require('node:fs');
const assert=require('node:assert/strict');
const ts=require('typescript');
const Module=require('node:module');
const file=require('node:path').resolve('src/songStructure.ts');
const mod=new Module(file,module);
mod._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,file);
const {readSong,songPatch,transposeChords}=mod.exports;
const slide=(id,title,body)=>({id,itemId:'song',title,body,order:0,enabled:true,elements:[{id:'text',type:'text',properties:{text:body}}]});
const original={id:'song',metadata:{},slides:[slide('v','Vers 1','Verse'),slide('c','Chorus','Chorus')]};
const before=JSON.stringify(original);
const structure=readSong(original);
structure.order.push(structure.sections[1].id);
const first=songPatch(original,structure);
assert.equal(first.slides.length,3);
assert.equal(structure.sections.length,2);
assert.equal(new Set(first.slides.map(slide=>slide.id)).size,3);
assert.equal(JSON.stringify(original),before);
const changed=structuredClone(structure);
changed.sections[1].slides[0].body='New chorus';
changed.sections[1].slides[0].elements[0].properties.text='New chorus';
const second=songPatch({...original,...first},changed);
assert.deepEqual(second.slides.slice(1).map(slide=>slide.body),['New chorus','New chorus']);
assert.deepEqual(second.slides.map(slide=>slide.id),first.slides.map(slide=>slide.id));
assert.deepEqual(JSON.parse(second.metadata.songOriginal).slides,original.slides);
assert.equal(transposeChords('[G] [C] [D/F#] [Em7]','G','A'),'[A] [D] [E/G#] [F#m7]');
assert.throws(()=>songPatch(original,{...structure,order:[]}));
console.log('PASS: repeated sections, stable IDs, immutable source, reset snapshot, transposition, empty order validation');
