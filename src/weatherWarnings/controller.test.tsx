import {act,cleanup,render} from '@testing-library/react';
import {afterEach,expect,it,vi} from 'vitest';
import {create} from 'zustand';
const mocks=vi.hoisted(()=>({presentation:null as any,output:null as any}));
vi.mock('../store',()=>({usePresentation:{getState:()=>mocks.presentation.getState(),subscribe:(fn:any)=>mocks.presentation.subscribe(fn)}}));
vi.mock('../liveOutputPreview',()=>({useLiveOutputPreview:{getState:()=>mocks.output.getState(),subscribe:(fn:any)=>mocks.output.subscribe(fn)}}));
import {WeatherWarningsController,useWeatherWarnings} from './controller';
import {usePreferences} from '../preferences';
afterEach(()=>{cleanup();vi.useRealTimers();vi.unstubAllGlobals()});
it('preloads warnings off air and publishes them immediately on the first eligible output',async()=>{
 vi.useFakeTimers();vi.setSystemTime(new Date('2026-10-25T10:00:00Z'));
 const now=Date.now(),warning={id:'wind',event:'Wind',headline:'Windwarnung',description:'Bitte vorsichtig sein.',severity:'Minor',areaName:'Bielefeld',source:'DWD',validFrom:new Date(now-1000).toISOString(),validUntil:new Date(now+3600000).toISOString()};
 const read=vi.fn().mockResolvedValue({status:'ready',fetchedAt:now,warnings:[warning]}),send=vi.fn();
 Object.defineProperty(window,'desktop',{configurable:true,value:{weatherWarnings:{read},sendWeatherWarnings:send}});
 mocks.presentation=create(()=>({onAir:false,items:[]}));
 mocks.output=create(()=>({slide:{bannerContext:{liveSection:'pre',countdownActive:false}}}));
 usePreferences.setState({weatherWarningsEnabled:true});
 render(<WeatherWarningsController quick={null}/>);
 await act(async()=>{});
 expect(read).toHaveBeenCalledTimes(1);
 expect(useWeatherWarnings.getState().state).toBeNull();
 act(()=>mocks.presentation.setState({onAir:true}));
 expect(useWeatherWarnings.getState().state?.items[0].id).toBe('wind');
 act(()=>usePreferences.getState().setWeatherWarningsEnabled(false));
 expect(useWeatherWarnings.getState().state).toBeNull();
 await act(async()=>{vi.advanceTimersByTime(61000)});
 expect(read).toHaveBeenCalledTimes(1);
 act(()=>usePreferences.getState().setWeatherWarningsEnabled(true));
 await act(async()=>{});
 expect(read).toHaveBeenCalledTimes(2);
 expect(send).toHaveBeenLastCalledWith(expect.objectContaining({items:[expect.objectContaining({id:'wind'})]}));
});
